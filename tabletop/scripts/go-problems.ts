/**
 * Writes src/games/go/practice/problems.json: Go problems generated from numbered seeds, every
 * one proved by a solver (src/games/go/practice/generate.ts). Repeatable: the same seeds give the
 * same problems.
 *
 *   npx tsx scripts/go-problems.ts              150 of each kind (50 nets)
 *   npx tsx scripts/go-problems.ts 40           fewer, for a quick look
 *   npx tsx scripts/go-problems.ts 150 life     only remake the life-and-death problems, keeping the rest
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { ProblemKind } from '../src/games/go/practice/generate';
import { generateProblems, KIND_PREFIX, PROBLEM_KINDS } from '../src/games/go/practice/generate';

type Row = [string, string, string, number, string];

const count = Number(process.argv[2] ?? 150);
const asked = process.argv.slice(3) as ProblemKind[];
for (const k of asked) if (!PROBLEM_KINDS.includes(k)) throw new Error(`Unknown kind ${k}; the kinds are ${PROBLEM_KINDS.join(', ')}`);
const kinds = asked.length > 0 ? asked : PROBLEM_KINDS;
const file = join(process.cwd(), 'src', 'games', 'go', 'practice', 'problems.json');
const kept = asked.length > 0 ? (JSON.parse(readFileSync(file, 'utf8')) as { problems: Row[] }).problems : [];
const started = Date.now();
const sets = generateProblems(count, kinds, (kind, made, tried) => {
  if (tried % 1000 === 0) console.log(`  ${kind}: ${made} from ${tried} seeds, ${((Date.now() - started) / 1000).toFixed(0)} s`);
});
const byKind = new Map<ProblemKind, Row[]>();
for (const kind of PROBLEM_KINDS) {
  const made = sets[kind];
  byKind.set(kind, made ? made.map((p): Row => [p.id, p.position, p.line.join(' '), p.rating, p.themes.join(' ')]) : kept.filter((r) => r[0].startsWith(KIND_PREFIX[kind])));
}
const problems = PROBLEM_KINDS.flatMap((kind) => byKind.get(kind) ?? []);
writeFileSync(file, `${JSON.stringify({ note: 'Generated by scripts/go-problems.ts; every problem proved by a solver.', problems })}\n`);
const counts = PROBLEM_KINDS.map((kind) => `${kind} ${byKind.get(kind)?.length ?? 0}`).join(', ');
console.log(`Wrote ${problems.length} problems (${counts}) in ${((Date.now() - started) / 1000).toFixed(0)} s.`);
