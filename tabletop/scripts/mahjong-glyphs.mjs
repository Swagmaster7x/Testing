/**
 * Writes src/games/mahjong/ui/glyphs.ts: the two dozen Chinese characters on the mahjong tiles,
 * taken from LXGW WenKai TC Bold (SIL Open Font License 1.1; licenses/LXGW-WenKai-TC-OFL.txt) as
 * plain SVG path data in a 100-unit box. No font file ships: only these outlines.
 *
 * The font and the parser are not app dependencies. To run it again:
 *   npm install --no-save @fontsource/lxgw-wenkai-tc@5.3.1 fontkit@3.0.0
 *   node scripts/mahjong-glyphs.mjs
 * (GLYPH_MODULES=<folder> reads them from another folder's node_modules.)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(process.env.GLYPH_MODULES ?? root, 'package.json'));
const fontkit = require('fontkit');
const pkg = dirname(require.resolve('@fontsource/lxgw-wenkai-tc/package.json'));

const CHARS = '一二三四五六七八九萬東南西北中發梅蘭菊竹春夏秋冬';
const FAMILY = 'lxgw-wenkai-tc';
const WEIGHT = 700;

const unicode = JSON.parse(readFileSync(join(pkg, 'unicode.json'), 'utf8'));

function subsetFor(codePoint) {
  for (const [subset, ranges] of Object.entries(unicode)) {
    for (const range of ranges.split(',')) {
      const r = range.trim().replace('U+', '');
      const [a, b] = r.includes('-') ? r.split('-').map((x) => parseInt(x, 16)) : [parseInt(r, 16), parseInt(r, 16)];
      if (codePoint >= a && codePoint <= b) return subset.replace(/[[\]]/g, '');
    }
  }
  throw new Error(`No subset has U+${codePoint.toString(16)}`);
}

const round = (n) => Math.round(n * 10) / 10;
const out = {};
for (const ch of CHARS) {
  const cp = ch.codePointAt(0);
  const font = fontkit.openSync(join(pkg, 'files', `${FAMILY}-${subsetFor(cp)}-${WEIGHT}-normal.woff2`));
  const glyph = font.glyphForCodePoint(cp);
  if (!glyph || glyph.id === 0) throw new Error(`The font has no ${ch}`);
  const scale = 100 / font.unitsPerEm;
  // Centre the em box: the box from descent to ascent becomes 0 to 100.
  const top = (font.ascent + font.descent) / 2 + font.unitsPerEm / 2;
  const left = (font.unitsPerEm - glyph.advanceWidth) / 2;
  const path = glyph.path.transform(scale, 0, 0, -scale, left * scale, top * scale);
  out[ch] = path.commands
    .map((c) => `${c.command === 'moveTo' ? 'M' : c.command === 'lineTo' ? 'L' : c.command === 'quadraticCurveTo' ? 'Q' : c.command === 'bezierCurveTo' ? 'C' : 'Z'}${c.args.map(round).join(' ')}`)
    .join('');
}

const lines = Object.entries(out).map(([ch, d]) => `  '${ch}': '${d}',`);
const file = `/**
 * Chinese characters for the mahjong tiles, from LXGW WenKai TC Bold
 * (Copyright 2024 The LXGW WenKai Project Authors, https://github.com/lxgw/LxgwWenkaiTC;
 * SIL Open Font License 1.1, licenses/LXGW-WenKai-TC-OFL.txt). Generated by
 * scripts/mahjong-glyphs.mjs: SVG path data in a 100-unit box, y down. Do not edit by hand.
 */
export const GLYPHS: Readonly<Record<string, string>> = {
${lines.join('\n')}
};
`;
writeFileSync(join(root, 'src/games/mahjong/ui/glyphs.ts'), file);
console.log(`Wrote ${Object.keys(out).length} glyphs, ${file.length} bytes.`);
