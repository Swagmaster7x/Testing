/**
 * npm run generate:brisca: endgame problems for Brisca practice (PLAN.md 2.6), proved by the
 * exact solver. Hands are played by level-3 bots until the stock is empty; a position becomes a
 * problem when the player to decide has exactly one best card (by at least MARGIN points) at every
 * decision of the line, with the other side answering perfectly. Writes
 * src/games/brisca/practice/endgames.json.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createRng } from '../src/core/rng';
import { chooseAction, solveMoves } from '../src/games/brisca/bots';
import type { BriscaState, Card } from '../src/games/brisca/rules';
import { brisca, PUERTO_RICO, viewOf } from '../src/games/brisca/rules';

const OUT = join(import.meta.dirname, '..', 'src', 'games', 'brisca', 'practice', 'endgames.json');
const WANT = Number(process.argv[2] ?? 160);
const MARGIN = 2;

interface Problem {
  id: string;
  position: string;
  setup: string | null;
  line: string[];
  rating: number;
  themes: string[];
}

function bestCards(s: BriscaState): { best: Card[]; margin: number; options: number } {
  const scored = solveMoves(s).sort((a, b) => b.points - a.points);
  const top = scored[0]?.points ?? 0;
  const best = scored.filter((m) => m.points === top).map((m) => m.card);
  const next = scored.find((m) => m.points < top)?.points;
  return { best, margin: next === undefined ? 0 : top - next, options: scored.length };
}

function play(s: BriscaState, card: Card): BriscaState {
  return brisca.apply(s, { type: 'play', card }).state;
}

/** The line from a position: the student's unique best cards, the other side's best answers. */
function lineFrom(start: BriscaState, student: number): { line: string[]; decisions: number; hard: number } | null {
  let s = start;
  const line: string[] = [];
  let decisions = 0;
  let hard = 0;
  for (let guard = 0; guard < 12; guard++) {
    const seat = brisca.turn(s);
    if (seat === null || s.handNo !== start.handNo || s.over) break;
    const { best, margin, options } = bestCards(s);
    if (seat === student) {
      if (options > 1) {
        if (best.length !== 1 || margin < MARGIN) return null;
        decisions++;
        if (margin < 6) hard++;
      }
      line.push(best[0] as string);
      s = play(s, best[0] as Card);
    } else {
      const card = [...best].sort()[0] as Card;
      line.push(card);
      s = play(s, card);
    }
  }
  return decisions > 0 ? { line, decisions, hard } : null;
}

const problems: Problem[] = [];
const seen = new Set<string>();
for (let i = 0; problems.length < WANT && i < WANT * 40; i++) {
  const rng = createRng(`brisca-endgames/${i}`);
  let s = brisca.setup(PUERTO_RICO, rng.fork('deal'));
  while (brisca.turn(s) !== null && s.stock.length > 0) {
    const seat = brisca.turn(s) ?? 0;
    s = brisca.apply(s, chooseAction(viewOf(s, seat), 3, rng.fork(`move/${i}/${s.won.flat().length}/${s.trick.length}`))).state;
  }
  if (brisca.turn(s) === null || s.trick.length !== 0) continue;
  const leader = brisca.turn(s) ?? 0;
  // Half the problems are led by the student; in the rest the other side leads first.
  const studentLeads = i % 2 === 0;
  const student = studentLeads ? leader : leader === 0 ? 1 : 0;
  let start = s;
  let setup: string | null = null;
  if (!studentLeads) {
    const { best } = bestCards(s);
    setup = [...best].sort()[0] ?? null;
    if (!setup) continue;
    start = play(s, setup as Card);
  }
  const found = lineFrom(start, student);
  if (!found) continue;
  const text = brisca.codec.state.toText(s);
  if (seen.has(text)) continue;
  seen.add(text);
  problems.push({
    id: `brisca-end:${i}`,
    position: text,
    setup,
    line: found.line,
    rating: 650 + 140 * (found.decisions - 1) + 120 * found.hard + (setup ? 60 : 0),
    themes: ['endgame', setup ? 'follow' : 'lead'],
  });
}
writeFileSync(OUT, `${JSON.stringify({ note: 'Generated by scripts/generate-brisca-endgames.ts; every line proved by the exact solver.', problems }).replace(/\},\{/g, '},\n{')}\n`);
console.log(`Wrote ${problems.length} problems to ${OUT}`);
