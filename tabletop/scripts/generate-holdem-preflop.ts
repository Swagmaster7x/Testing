/**
 * npm run generate:holdem: the strength of all 169 starting hands, for the bots' ranges and the
 * preflop chart. For each hand class, its equity against one random hand (heads-up) and against
 * three random hands (a four-way pot), by Monte Carlo with a fixed seed. Hands are ranked by the
 * mean of the two, each measured against its fair share (one half, one quarter), so pairs and
 * high cards (strong heads-up) and suited connected cards (strong in many-way pots) both count.
 * A small playability bonus is added for what all-in equity misses: pairs flop sets, suited hands
 * flop flushes and draws, connected cards make straights (a bigger bonus the fewer gaps). With it
 * the top 15, 20, 27 and 45 per cent of hands look like the usual six-handed opening ranges from
 * under the gun, the hijack, the cutoff and the button.
 * Writes src/games/holdem/preflop.json.
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createRng } from '../src/core/rng';
import { HAND_CLASSES } from '../src/games/holdem/cards';
import { ANY_HAND, combosOf, rangeEquity } from '../src/games/holdem/equity';

const OUT = join(import.meta.dirname, '..', 'src', 'games', 'holdem', 'preflop.json');
const SAMPLES = Number(process.argv[2] ?? 40_000);

const RANKS = '23456789TJQKA';

/** What all-in equity misses: sets, flushes and straights made after the flop. */
function playability(cls: string): number {
  if (cls.length === 2) return 0.17;
  const high = RANKS.indexOf(cls[0] ?? '');
  const low = RANKS.indexOf(cls[1] ?? '');
  const suited = cls[2] === 's';
  const gap = high - low - 1;
  let x = suited ? 0.045 : -0.01;
  if (gap === 0) x += suited ? 0.08 : 0.02;
  else if (gap === 1) x += suited ? 0.045 : 0.01;
  else if (gap === 2) x += suited ? 0.015 : 0;
  if (suited && cls[0] === 'A') x += 0.025;
  return x;
}

const rows = HAND_CLASSES.map((cls, i) => {
  const combos = combosOf(cls);
  const rng = createRng(`preflop/${cls}`);
  // Spread the samples over the suit combinations of the class.
  const per = Math.ceil(SAMPLES / combos.length);
  let one = 0;
  let three = 0;
  for (const c of combos) {
    one += rangeEquity(c, [], [ANY_HAND], per, rng);
    three += rangeEquity(c, [], [ANY_HAND, ANY_HAND, ANY_HAND], Math.ceil(per / 2), rng);
  }
  one /= combos.length;
  three /= combos.length;
  if (i % 20 === 0) process.stdout.write(`${cls} `);
  return { cls, combos: combos.length, vs1: Math.round(one * 10000) / 10000, vs3: Math.round(three * 10000) / 10000, score: (one / 0.5 + three / 0.25) / 2 + playability(cls) };
});
rows.sort((a, b) => b.score - a.score);
const json = {
  note: 'Generated by scripts/generate-holdem-preflop.ts: equity of each starting hand against one and against three random hands; best first by those and a playability bonus.',
  samples: SAMPLES,
  hands: rows.map(({ cls, combos, vs1, vs3 }) => ({ cls, combos, vs1, vs3 })),
};
writeFileSync(OUT, `${JSON.stringify(json, null, 1)}\n`);
console.log(`\nwrote ${rows.length} hands to ${OUT}`);
console.log(rows.slice(0, 40).map((r) => r.cls).join(' '));
