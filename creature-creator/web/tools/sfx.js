// Packs the short sound effects in web/audio/*.ogg into src/sfx-data.js as base64, so they load
// without any network or file request (which a page opened from the APK's assets cannot make).
// Music is not packed: it is streamed from app/src/main/assets/www/audio/*.mp3.
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'audio'), out = path.join(__dirname, '..', 'src', 'sfx-data.js');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.ogg')).sort();
const body = files.map((f) => `  ${JSON.stringify(f.replace('.ogg', ''))}: ${JSON.stringify(fs.readFileSync(path.join(dir, f)).toString('base64'))},`).join('\n');
fs.writeFileSync(out, '// Generated by tools/sfx.js from web/audio/*.ogg. Do not edit.\nexport const SFX_DATA = {\n' + body + '\n};\n');
console.log('packed', files.length, 'sounds,', Math.round(fs.statSync(out).size / 1024), 'KB');
